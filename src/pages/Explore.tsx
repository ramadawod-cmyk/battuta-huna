import { useEffect, useMemo, useState } from "react";
import { useSearchParams } from "react-router-dom";
import TagPill from "../components/TagPill";
import PoiCard from "../components/PoiCard";
import SiteDetailModal from "../components/SiteDetailModal";
import UnsplashCredit from "../components/UnsplashCredit";
import { useCity } from "../lib/CityContext";
import { useTranslation } from "../lib/LanguageContext";
import { useWikiThumbnail } from "../lib/useWikiThumbnail";
import { haversineMeters, getCurrentPosition } from "../lib/geo";
import { ensureCitySites } from "../lib/sites";
import { CATEGORIES as SITE_CATEGORIES, CATEGORY_ACCENTS, CATEGORY_LABEL_KEYS, normalizeCategory } from "../lib/categories";
import { track } from "../lib/analytics";
import { useTrackScreen } from "../lib/useTrackScreen";
import type { Site } from "../lib/types";

const CATEGORIES = [
  "All",
  ...SITE_CATEGORIES,
];

function formatDistance(meters: number | null): string {
  if (meters === null) return "";
  if (meters < 1000) return `${Math.round(meters)} M`;
  return `${(meters / 1000).toFixed(1)} KM`;
}

function PoiCardWithImage({
  site,
  distance,
  onClick,
}: {
  site: Site;
  distance: string;
  onClick: () => void;
}) {
  const { t, language } = useTranslation();
  const imageUrl = useWikiThumbnail(site.name);
  const name = language === "ar" && site.name_ar ? site.name_ar : site.name;
  const description = language === "ar" && site.description_ar ? site.description_ar : site.description;
  return (
    <PoiCard
      name={name}
      distance={distance}
      category={t(CATEGORY_LABEL_KEYS[normalizeCategory(site.category)]).toUpperCase()}
      description={description}
      imageUrl={site.image_url || imageUrl}
      categoryAccent={CATEGORY_ACCENTS[normalizeCategory(site.category)]}
      onClick={onClick}
    />
  );
}

export default function Explore() {
  const homeCity = useCity();
  const { t } = useTranslation();
  const [searchParams] = useSearchParams();
  const [activeCategory, setActiveCategory] = useState("All");
  const [userPos, setUserPos] = useState<{ lat: number; lng: number } | null>(null);
  const [heroImageFailed, setHeroImageFailed] = useState(false);
  const [heroFallbackFailed, setHeroFallbackFailed] = useState(false);
  const [selectedSiteName, setSelectedSiteName] = useState<string | null>(() => searchParams.get("site"));

  // Query params let a link (e.g. the Plan page's suggestions panel) show someone ELSE's city --
  // read once on mount, same convention TripMapBuilder.tsx uses for its `day` param, deliberately
  // not reactive. When present, this page shows that city via a local fetch instead of the
  // viewer's own detected location, and never touches useCity()/locate() or the user's stored
  // home city at all.
  const [override] = useState(() => {
    const cityId = searchParams.get("cityId");
    const cityName = searchParams.get("cityName");
    const countryId = searchParams.get("countryId");
    const countryName = searchParams.get("countryName");
    if (!cityId || !cityName || !countryId || !countryName) return null;
    return { id: cityId, name: cityName, countryId, countryName, locality: null as string | null };
  });
  const [overrideSites, setOverrideSites] = useState<Site[] | null>(null);
  const [overrideError, setOverrideError] = useState<string | null>(null);
  const [overrideReloadKey, setOverrideReloadKey] = useState(0);

  useEffect(() => {
    if (!override) return;
    setOverrideSites(null);
    setOverrideError(null);
    ensureCitySites(override.id, override.name, override.countryId, override.countryName)
      .then(setOverrideSites)
      .catch((err) => setOverrideError(err instanceof Error ? err.message : t("explore.loadFailed")));
  }, [override, overrideReloadKey, t]);

  const city = override || homeCity.city;
  const sites = override ? overrideSites || [] : homeCity.sites;
  const status = override ? (overrideError ? "error" : overrideSites === null ? "loading-sites" : "ready") : homeCity.status;
  const error = override ? overrideError : homeCity.error;
  const locate = override ? () => setOverrideReloadKey((k) => k + 1) : homeCity.locate;

  // heroImageUrl comes from a cached DB value (CityContext's getCityHero) that can go stale --
  // e.g. a thumbnail URL generated by older code that Wikimedia's resizer now rejects. If it
  // fails to load, fall back to a fresh title lookup instead of giving up to a flat gradient.
  // In override mode there's no cached hero value at all (that lives on CityContext), so this
  // always falls straight to the fresh wiki lookup.
  const heroImageUrl = override ? null : homeCity.heroImageUrl;
  const freshHeroImageUrl = useWikiThumbnail(city?.name);
  const heroImagePrimaryOk = Boolean(heroImageUrl) && !heroImageFailed;
  const heroImageFallbackOk =
    !heroImagePrimaryOk && Boolean(freshHeroImageUrl) && freshHeroImageUrl !== heroImageUrl && !heroFallbackFailed;
  const displayedHeroUrl = heroImagePrimaryOk ? heroImageUrl : heroImageFallbackOk ? freshHeroImageUrl : null;

  useTrackScreen("explore");

  useEffect(() => {
    setHeroImageFailed(false);
    setHeroFallbackFailed(false);
  }, [heroImageUrl]);

  useEffect(() => {
    if (override) return;
    if (homeCity.status === "idle") {
      homeCity.locate();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [override, homeCity.status]);

  useEffect(() => {
    if (override) return;
    if (status === "ready" && !userPos) {
      getCurrentPosition()
        .then((pos) => setUserPos({ lat: pos.coords.latitude, lng: pos.coords.longitude }))
        .catch(() => {});
    }
  }, [override, status, userPos]);

  const visibleSites =
    activeCategory === "All" ? sites : sites.filter((s) => s.category === activeCategory);

  const sitesWithDistance = useMemo(
    () =>
      visibleSites
        .map((site) => ({
          site,
          distanceMeters: userPos ? haversineMeters(userPos.lat, userPos.lng, site.lat, site.lng) : null,
        }))
        .sort((a, b) => (a.distanceMeters ?? 0) - (b.distanceMeters ?? 0)),
    [visibleSites, userPos],
  );

  return (
    <div className="px-4 sm:px-6 md:px-8 lg:px-[32px] py-6 md:py-[32px] max-w-[1260px]">
      <p className="font-heading font-semibold text-[20px] sm:text-[24px] text-text-primary">
        {city?.name || t("explore.locating")}
      </p>
      <p className="font-medium text-[11px] text-text-secondary tracking-[1px] mt-[4px]">{t("explore.culturalDiscovery")}</p>

      <div className="relative bg-secondary-purple rounded-[24px] w-full h-[320px] overflow-hidden mt-[16px]">
        {displayedHeroUrl ? (
          <img
            src={displayedHeroUrl}
            alt={city?.name || ""}
            onError={() => {
              if (heroImagePrimaryOk) {
                setHeroImageFailed(true);
                track("Hero Image Broken", { city_id: city?.id, recovered: false });
              } else {
                setHeroFallbackFailed(true);
                track("Hero Image Broken", { city_id: city?.id, recovered: false, fallback: true });
              }
            }}
            className="absolute inset-0 size-full object-cover"
          />
        ) : (
          <div className="absolute inset-0 bg-gradient-to-r from-[#2d2a5c] to-secondary-purple" />
        )}
        {heroImagePrimaryOk && !override && homeCity.heroImageCredit && (
          <UnsplashCredit name={homeCity.heroImageCredit.name} profileUrl={homeCity.heroImageCredit.profileUrl} />
        )}
      </div>

      <p className="font-medium text-[12px] text-text-primary tracking-[0.48px] mt-[24px]">
        {status === "locating" && t("explore.findingPlace")}
        {status === "loading-sites" &&
          (override ? t("explore.gatheringSitesFor", { city: override.name }) : t("explore.gatheringSites"))}
        {status === "ready" &&
          (override
            ? t("explore.topSitesIn", { city: override.name, count: sites.length })
            : t("explore.nearbyWithinRange", { count: sites.length }))}
        {status === "error" && (error || t("explore.locationUnavailable"))}
        {status === "idle" && t("explore.findingPlace")}
        {city?.locality ? ` · ${city.locality.toUpperCase()}` : ""}
      </p>
      {status === "error" && (
        <button
          onClick={locate}
          className="mt-[10px] bg-secondary-purple text-white text-[12px] font-medium rounded-[16px] px-[14px] py-[6px]"
        >
          {t("explore.tryAgain")}
        </button>
      )}

      <div className="flex gap-[10px] mt-[16px] flex-wrap">
        {CATEGORIES.map((cat) => (
          <TagPill
            key={cat}
            label={cat === "All" ? t("explore.allCategories") : t(CATEGORY_LABEL_KEYS[cat])}
            active={activeCategory === cat}
            onClick={() => {
              track("Site Filter Toggled", { tag: cat, active: activeCategory !== cat, view: "nearby" });
              setActiveCategory(cat);
            }}
          />
        ))}
      </div>

      <div className="flex flex-wrap gap-[20px] mt-[20px]">
        {sitesWithDistance.map(({ site, distanceMeters }) => (
          <PoiCardWithImage
            key={site.id}
            site={site}
            distance={formatDistance(distanceMeters)}
            onClick={() => setSelectedSiteName(site.name)}
          />
        ))}
        {status === "ready" && sitesWithDistance.length === 0 && (
          <p className="text-text-secondary text-[14px]">{t("explore.noSitesForCategory")}</p>
        )}
      </div>

      {selectedSiteName && city && (
        <SiteDetailModal
          siteName={selectedSiteName}
          cityId={city.id}
          cityName={city.name}
          source="explore"
          onClose={() => setSelectedSiteName(null)}
        />
      )}
    </div>
  );
}
